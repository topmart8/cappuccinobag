export function buildFaqSchema(faqs) {
  return {
    "@type": "FAQPage",
    mainEntity: faqs.map(({ question, answer }) => ({
      "@type": "Question",
      name: question,
      acceptedAnswer: { "@type": "Answer", text: answer },
    })),
  };
}

export function buildCaseStudySchema(caseStudy) {
  const canonical = `${caseStudySiteUrl}${caseStudy.url}`;
  const product = {
    "@type": "Product",
    "@id": `${canonical}#product`,
    name: caseStudy.productName,
    description: caseStudy.summary,
    category: caseStudy.productCategory,
    url: canonical,
    brand: { "@type": "Brand", name: "Cappuccino" },
    manufacturer: { "@id": `${caseStudySiteUrl}/#organization` },
    audience: {
      "@type": "BusinessAudience",
      audienceType: caseStudy.audience,
    },
    additionalProperty: caseStudy.solutions.map((value) => ({
      "@type": "PropertyValue",
      name: "Development scope",
      value,
    })),
  };

  if (caseStudy.image) product.image = `${caseStudySiteUrl}${caseStudy.image}`;

  return {
    "@context": "https://schema.org",
    "@graph": [
      organizationSchema,
      {
        "@type": "Article",
        "@id": `${canonical}#case-study`,
        headline: caseStudy.title,
        description: caseStudy.metaDescription,
        url: canonical,
        mainEntityOfPage: canonical,
        about: { "@id": `${canonical}#product` },
        author: { "@id": `${caseStudySiteUrl}/#organization` },
        publisher: { "@id": `${caseStudySiteUrl}/#organization` },
        datePublished: "2026-08-09",
        dateModified: "2026-08-09",
      },
      product,
      buildFaqSchema(caseStudy.faqs),
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "Home", item: `${caseStudySiteUrl}/` },
          { "@type": "ListItem", position: 2, name: "Case Studies", item: `${caseStudySiteUrl}/case-studies` },
          { "@type": "ListItem", position: 3, name: caseStudy.client, item: canonical },
        ],
      },
    ],
  };
}
